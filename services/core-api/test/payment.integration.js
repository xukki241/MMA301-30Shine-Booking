const { test } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
const { createModels } = require('../src/models');
const { createApp } = require('../src/app');
const { createPaymentRepository } = require('../src/payments/repository');

test('SePay sandbox: ownership, completed-only, exact matching, atomic settlement and replay', async t => {
  const connection = await mongoose.createConnection('mongodb://127.0.0.1:27017/shine_payment_tests').asPromise();
  const models = createModels(connection);
  const repository = createPaymentRepository(models, { accountNumber: '0000000001', bankCode: 'MB' });
  await repository.init();
  const customerId = new mongoose.Types.ObjectId();
  const stylistId = new mongoose.Types.ObjectId();
  const branchId = new mongoose.Types.ObjectId();
  const service = await models.Service.create({ branchId, name: 'Payment test', price: 10000, durationMinutes: 30 });
  const appointmentId = new mongoose.Types.ObjectId();
  await models.Calendar.create({ _id: stylistId, appointments: [{ _id: appointmentId, customerId, stylistId, branchId, serviceId: service._id, status: 'booked', startTime: new Date('2030-01-01T10:00:00Z'), endTime: new Date('2030-01-01T10:30:00Z') }] });
  const secret = 'a'.repeat(64);
  const app = createApp({ secret, models, paymentRepository: repository, paymentConfig: { webhookKey: 'webhook-test' } });
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await models.Calendar.deleteOne({ _id: stylistId }); await models.Service.deleteOne({ _id: service._id }); await repository.receipts.deleteMany({ appointmentId: String(appointmentId) }); await connection.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const token = id => jwt.sign({ role: 'customer' }, secret, { subject: String(id), expiresIn: 3600 });
  const request = (route, body, authorization = `Bearer ${token(customerId)}`) => fetch(base + route, { method: body === undefined ? 'GET' : 'POST', headers: { 'Content-Type': 'application/json', Authorization: authorization }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const create = () => request('/payments', { appointmentId: String(appointmentId) });
  assert.equal((await create()).status, 409);
  await models.Calendar.updateOne({ _id: stylistId }, { $set: { 'appointments.0.status': 'completed' } });
  assert.equal((await request('/payments', { appointmentId: String(appointmentId) }, `Bearer ${token(new mongoose.Types.ObjectId())}`)).status, 403);
  assert.equal((await request(`/appointments/${appointmentId}/pay`, {})).status, 409);
  assert.equal((await request('/payments', { appointmentId: String(appointmentId), amount: 1 })).status, 400);
  const created = await Promise.all([create(), create()]);
  const payments = await Promise.all(created.map(r => r.json()));
  assert.equal(payments[0].payment.reference, payments[1].payment.reference);
  const payment = payments[0].payment;
  assert.equal(payment.amount, 10000);
  const event = { id: Date.now(), transferType: 'in', transferAmount: 10000, accountNumber: '0000000001', gateway: 'MBBank', content: payment.reference };
  const webhook = (body, key = 'webhook-test') => request('/webhooks/sepay', body, `Apikey ${key}`);
  assert.equal((await webhook(event, 'wrong')).status, 401);
  for (const change of [{ transferAmount: 1 }, { accountNumber: 'wrong' }, { gateway: 'WrongBank' }, { transferType: 'out' }, { content: 'SHINEUNKNOWN' }]) await webhook({ ...event, ...change });
  assert.equal((await (await request(`/payments/${appointmentId}`)).json()).payment.status, 'pending');
  const results = await Promise.all([webhook(event), webhook(event)]);
  assert.deepEqual(await results[0].json(), { success: true });
  assert.equal(results[1].status, 200);
  const settled = await (await request(`/payments/${appointmentId}`)).json();
  assert.equal(settled.payment.status, 'paid');
  const calendar = await models.Calendar.findById(stylistId).lean();
  assert.equal(calendar.appointments[0].status, 'paid');
  assert.equal(await repository.receipts.countDocuments({ transactionId: String(event.id) }), 1);
  // A fresh repository instance still reads persisted payment state.
  const reopened = createPaymentRepository(models, { accountNumber: '0000000001', bankCode: 'MB' });
  assert.equal((await reopened.get(String(appointmentId), { userId: String(customerId), role: 'customer' })).status, 'paid');
  assert.equal((await request(`/payments/${appointmentId}`, undefined, `Bearer ${token(new mongoose.Types.ObjectId())}`)).status, 403);
});
